def recode(df: pd.DataFrame, ecuador_cct: bool) -> pd.DataFrame:
    df = df.copy()
    for r in RECODE.itertuples():
        if r.country == "Ecuador" and not ecuador_cct:
            continue
        m = df["country"] == r.country
        df.loc[m, "eventualcct"] = 1
        df.loc[m, "cctyear"] = r.cctyear_new
        df.loc[m, "yearfromcct"] = df.loc[m, "year"] - r.cctyear_new
    df["post_cct"] = (df["yearfromcct"] > 0).astype(int)
    return df


