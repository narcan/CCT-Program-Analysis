def matches(value: float, printed: str) -> bool:
    """True if value rounds to the printed string at the printed precision
    (significant digits for numbers printed below 0.001 in absolute value)."""
    p = float(printed)
    digits = printed.split(".")[1] if "." in printed else ""
    if abs(p) < 0.001 and p != 0:
        sig = len(digits.lstrip("0"))
        return float(f"{value:.{sig}g}") == float(f"{p:.{sig}g}")
    return round(value, len(digits)) == round(p, len(digits))


