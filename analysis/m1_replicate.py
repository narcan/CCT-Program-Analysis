def md_table(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> None:
    cols = list(df.columns)
    md("| " + " | ".join(str(c) for c in cols) + " |")
    md("|" + "---|" * len(cols))
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("" if np.isnan(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        md("| " + " | ".join(cells) + " |")
    md()


def stars(p: float) -> str:
    return "***" if p < 0.001 else "**" if p < 0.01 else "*" if p < 0.05 else ""


def ols(formula: str, data: pd.DataFrame, robust: bool = True):
    m = smf.ols(formula, data=data)
    return m.fit(cov_type="HC1", use_t=True) if robust else m.fit()


def rows_for(fit, terms, hc3: bool = False, **extra):
    out = []
    f3 = fit.model.fit(cov_type="HC3", use_t=True) if hc3 else None
    for t in terms:
        r = {**extra, "term": t, "coef": fit.params[t], "se": fit.bse[t],
             "t": fit.tvalues[t], "p": fit.pvalues[t], "n": int(fit.nobs)}
        if hc3:
            r["p_hc3"] = f3.pvalues[t]
        out.append(r)
    return out


