def survey_changes(df: pd.DataFrame, level: str, prefix: str) -> pd.DataFrame:
    """Annualized change between consecutive observed (non-interpolated) surveys of
    `level`, per country: g = (x_t / x_s) ** (1 / (t - s)) - 1, assigned to year t.
    GDP and Gini changes are annualized over the same interval from the i* series;
    a flag marks Gini endpoints that are interpolated."""
    out = []
    for c, g in df.groupby("country", sort=True):
        g = g.set_index("year")
        obs = g.loc[g[level].notna() & (g[level] > 0)]
        yrs = obs.index.to_list()
        for s, t in zip(yrs[:-1], yrs[1:]):
            gap = t - s
            row = {"country": c, "year": t, "year_prev": s, "gap": gap,
                   f"{prefix}_ann": (obs.at[t, level] / obs.at[s, level]) ** (1 / gap) - 1}
            for v, name in [("igovgdpppp", "gdp_ann"), ("igovgini", "gini_ann")]:
                a, b = g.at[t, v], g.at[s, v]
                row[name] = (a / b) ** (1 / gap) - 1 if (a > 0 and b > 0) else np.nan
            row["gini_interp_endpoint"] = int(g.at[t, "igovgini_interp"] == 1
                                              or g.at[s, "igovgini_interp"] == 1)
            out.append(row)
    return pd.DataFrame(out)


